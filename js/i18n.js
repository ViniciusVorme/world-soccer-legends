let currentLang = 'en';

const DEFAULT_LANG = 'en';

export function getLang() {
  return currentLang;
}

export function hydrateLangFromStorage() {
  const saved = getItem(STORAGE_KEY);
  if (saved === 'pt' || saved === 'en') {
    currentLang = saved;
    document.documentElement.lang = saved === 'en' ? 'en' : 'pt-BR';
    document.title = t('pageTitle');
  }
}

export function setLang(lang) {
  if (lang !== 'pt' && lang !== 'en') return;
  currentLang = lang;
  setItem(STORAGE_KEY, lang);
  document.documentElement.lang = lang === 'en' ? 'en' : 'pt-BR';
  document.title = t('pageTitle');
}

export function initLang() {
  try {
    const saved = getItem(STORAGE_KEY);
    if (saved === 'pt' || saved === 'en') currentLang = saved;
    else currentLang = DEFAULT_LANG;
  } catch (_) {
    currentLang = DEFAULT_LANG;
  }
  document.documentElement.lang = currentLang === 'en' ? 'en' : 'pt-BR';
}

export function t(key, params = {}) {
  let str = MESSAGES[currentLang]?.[key] ?? MESSAGES.en[key] ?? MESSAGES.pt[key] ?? key;
  for (const [k, v] of Object.entries(params)) {
    str = str.replaceAll(`{${k}}`, String(v));
  }
  return str;
}

export function divisionLabel(div) {
  if (div === 1) return t('serieA');
  if (div === 2) return t('serieB');
  return t('serieC');
}

export function getPositionLabel(code) {
  return POSITION_LABELS[currentLang]?.[code] ?? POSITION_LABELS.en[code] ?? POSITION_LABELS.pt[code] ?? code;
}

export function getFilterPositionLabel(code) {
  return FILTER_POSITION_LABELS[currentLang]?.[code] ?? FILTER_POSITION_LABELS.en[code] ?? FILTER_POSITION_LABELS.pt[code] ?? code;
}

export function getStatCategoryMeta(stat) {
  const map = {
    goals: { tab: t('statGoalsTab'), column: t('statGoalsCol'), empty: t('statGoalsEmpty') },
    assists: { tab: t('statAssistsTab'), column: t('statAssistsCol'), empty: t('statAssistsEmpty') },
    fouls: { tab: t('statFoulsTab'), column: t('statFoulsCol'), empty: t('statFoulsEmpty') },
    yellowCards: { tab: t('statYellowsTab'), column: t('statYellowsCol'), empty: t('statYellowsEmpty') },
    redCards: { tab: t('statRedsTab'), column: t('statRedsCol'), empty: t('statRedsEmpty') }
  };
  return map[stat] || map.goals;
}

export function getNarration() {
  return NARRATION[currentLang] || NARRATION.en || NARRATION.pt;
}

export function populatePositionFilter(selectEl) {
  if (!selectEl) return;
  const value = selectEl.value;
  const codes = ['GOL', 'ZAG', 'LD', 'LE', 'VOL', 'MC', 'MEI', 'MD', 'ME', 'PD', 'PE', 'CA'];
  selectEl.innerHTML = `<option value="">${t('allPositions')}</option>` +
    codes.map(code => `<option value="${code}">${getFilterPositionLabel(code)}</option>`).join('');
  if ([...selectEl.options].some(o => o.value === value)) selectEl.value = value;
}

export function syncLangButtons() {
  document.querySelectorAll('.lang-option[data-lang]').forEach(btn => {
    const active = btn.dataset.lang === currentLang;
    btn.classList.toggle('active', active);
    btn.setAttribute('aria-checked', String(active));
  });
}

export function syncStartDivisionHint(division) {
  const hint = document.getElementById('start-hint');
  if (!hint) return;
  if (division === undefined) {
    const active = document.querySelector('.start-division-option.active');
    division = active ? parseInt(active.dataset.division, 10) : 2;
  }
  hint.textContent = t(division === 1 ? 'startHintA' : 'startHintB');
}

export function applyStaticTranslations() {
  document.title = t('pageTitle');

  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });

  document.querySelectorAll('.table-scroll-btn-prev').forEach(el => {
    el.setAttribute('aria-label', t('scrollTableLeft'));
  });
  document.querySelectorAll('.table-scroll-btn-next').forEach(el => {
    el.setAttribute('aria-label', t('scrollTableRight'));
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });

  syncLangButtons();
  syncStartDivisionHint();

  populatePositionFilter(document.getElementById('filter-position'));

  const forceFilter = document.getElementById('filter-force');
  if (forceFilter) {
    const v = forceFilter.value;
    forceFilter.innerHTML = `
      <option value="0">${t('anyStrength')}</option>
      <option value="85">85+</option>
      <option value="80">80+</option>
      <option value="75">75+</option>`;
    forceFilter.value = v;
  }

  const legendFilter = document.getElementById('filter-legend');
  if (legendFilter) {
    const v = legendFilter.value;
    legendFilter.innerHTML = `
      <option value="">${t('allPlayers')}</option>
      <option value="true">${t('legends')}</option>
      <option value="false">${t('nonLegends')}</option>`;
    legendFilter.value = v;
  }

  const sortFilter = document.getElementById('filter-sort');
  if (sortFilter) {
    const v = sortFilter.value;
    const validSort = ['budget-first', 'price-asc', 'price-desc', 'force'];
    const selected = validSort.includes(v) ? v : 'budget-first';
    sortFilter.innerHTML = `
      <option value="budget-first"${selected === 'budget-first' ? ' selected' : ''}>${t('sortBudgetFirst')}</option>
      <option value="price-asc"${selected === 'price-asc' ? ' selected' : ''}>${t('sortPriceAsc')}</option>
      <option value="price-desc"${selected === 'price-desc' ? ' selected' : ''}>${t('sortPriceDesc')}</option>
      <option value="force"${selected === 'force' ? ' selected' : ''}>${t('sortForce')}</option>`;
    sortFilter.value = selected;
  }

  const clubInput = document.getElementById('club-name');
  if (clubInput && (clubInput.value === 'Meu Clube FC' || clubInput.value === 'My Club FC')) {
    clubInput.value = t('defaultClubName');
  }
}
